#!/usr/bin/env node
// Renders scripts/og-card.html to a 1200x630 PNG and writes it into the Worker as
// src/worker/wiki-og.ts. Run it after editing the card: `npm run og`.
//
// WHY THE BYTES GO INTO A .ts MODULE instead of being imported as a file. wrangler can bundle a
// .png with a `Data` rule, but `npm test` runs the Worker's own sources through `node --test`, and
// Node cannot import a .png -- one `import og from "./og.png"` in wiki-app.ts would take
// wiki-app.test.ts down with it. base64 in a module is the one form that both the bundler and the
// test runner can read, and it keeps the promise wiki-app.ts makes about the page itself: nothing
// to build, and no asset host to depend on.
//
// WHY CHROME. The card is CSS, so the thing that renders it has to be a browser; and the fonts are
// Hanken Grotesk and DM Mono from Google Fonts, which is also why this needs the network and why
// --virtual-time-budget is generous. A run with the fonts unreachable still produces a PNG -- it
// just silently falls back to system faces, which is the one failure worth looking at the output
// for. The check below catches the size and the dimensions, not the typeface.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const CARD = join(here, "og-card.html");
const OUT = join(root, "src", "worker", "wiki-og.ts");
const [W, H] = [1200, 630];

const chrome =
  process.env.CHROME ??
  [
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
  ].find((p) => existsSync(p));
if (chrome === undefined) {
  console.error("no Chrome or Chromium found. Set CHROME=/path/to/chrome and run again.");
  process.exit(1);
}

const dir = mkdtempSync(join(tmpdir(), "hlekk-og-"));
try {
  const png = join(dir, "og.png");
  execFileSync(
    chrome,
    [
      "--headless",
      "--disable-gpu",
      "--hide-scrollbars",
      `--window-size=${W},${H}`,
      // The fonts are fetched; this is how long the renderer waits for them.
      "--virtual-time-budget=8000",
      `--user-data-dir=${join(dir, "profile")}`,
      `--screenshot=${png}`,
      pathToFileURL(CARD).href,
    ],
    { stdio: ["ignore", "ignore", "ignore"] },
  );

  const bytes = readFileSync(png);
  // A PNG's IHDR is fixed-position: 8 bytes of signature, 8 of chunk header, then w and h.
  const magic = "89504e470d0a1a0a";
  if (bytes.subarray(0, 8).toString("hex") !== magic) throw new Error("the renderer did not produce a PNG");
  const [w, h] = [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
  if (w !== W || h !== H) throw new Error(`rendered ${w}x${h}, expected ${W}x${H}`);

  const base64 = bytes.toString("base64");
  const etag = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
  // 76 columns is the one wrapping that keeps the file openable in an editor without a 100 KB line.
  const wrapped = (base64.match(/.{1,76}/g) ?? []).map((line) => `  "${line}" +`).join("\n").replace(/ \+$/, "");

  writeFileSync(
    OUT,
    `// GENERATED by scripts/make-og.mjs from scripts/og-card.html. Do not edit by hand: edit the
// card and run \`npm run og\`.
//
// The social card the Worker serves at /og.png, in the bundle rather than on an asset host, for
// the reason the page itself is in the bundle. See the generator for why these bytes are base64 in
// a module and not an imported file.

/** The rendered card, ${W}x${H}, ${bytes.length.toLocaleString("en-US")} bytes. */
export const OG_CARD_BASE64 =
${wrapped};

/** Decoded once, when the isolate loads, so a request copies nothing. */
export const OG_CARD: Uint8Array<ArrayBuffer> = Uint8Array.from(atob(OG_CARD_BASE64), (c) => c.charCodeAt(0));

export const OG_CARD_WIDTH = ${W};
export const OG_CARD_HEIGHT = ${H};

/** The bytes' own hash, so a crawler that already has the card revalidates instead of refetching. */
export const OG_CARD_ETAG = '"${etag}"';
`,
  );

  console.log(`wrote ${OUT}`);
  console.log(`  ${W}x${H}, ${bytes.length.toLocaleString("en-US")} bytes, etag ${etag}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
